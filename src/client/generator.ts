/**
 * Pure schema → TypeScript source generator.
 *
 * Written against structural `BaseLike` types (not SDK classes) so it can run
 * against a real `Base` from `@airtable/blocks/models` inside the extension
 * AND against plain fixture objects in Node tests.
 *
 * Generated value types mirror what `record.getCellValue(field)` returns in
 * the Blocks SDK (rich shapes: select choices carry id/name/color, record
 * links are {id, name}[], collaborators have email/avatar) — NOT the flatter
 * REST API shapes.
 */

import {computeSchemaSignature} from './schema-signature.js';

export interface FieldLike {
  id: string;
  name: string;
  type: string;
  description?: string | null;
  options?: {[key: string]: unknown} | null;
  /**
   * The SDK's `Field.isComputed`: true when the value is derived, not set by
   * user input. Optional so plain fixtures and older callers still work; when
   * absent, writability is decided from the field type alone.
   */
  isComputed?: boolean;
}

export interface TableLike {
  id: string;
  name: string;
  description?: string | null;
  fields: ReadonlyArray<FieldLike>;
  /** The SDK's `Table.primaryField`, read structurally (only its id is used). */
  primaryField?: {id: string} | null;
}

export interface BaseLike {
  id: string;
  name?: string;
  tables: ReadonlyArray<TableLike>;
}

